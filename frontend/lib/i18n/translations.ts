export function getTranslation(locale: Locale, key: string, fallback?: string): string {
  const dict = translations[locale] || translations.vi;
  return (dict as any)[key] || (translations.vi as any)[key] || fallback || key;
}

export function getRouteTitle(pathname: string, locale: Locale = 'vi'): string {
  const t = (k: string, fb: string) => getTranslation(locale, k, fb);

  if (pathname === '/admin') return t('nav.hub', 'Cổng điều hành trung tâm');
  if (pathname === '/admin/dashboard') return t('nav.dashboard', 'Tổng quan');
  if (pathname.startsWith('/admin/reports')) return t('nav.reports', 'Báo cáo');
  if (pathname === '/admin/orders') return t('nav.orders', 'Đơn hàng');
  if (pathname.startsWith('/admin/orders/')) return t('nav.orderDetails', 'Chi tiết đơn hàng');
  if (pathname.startsWith('/admin/reservations')) return t('nav.reservations', 'Đặt bàn');
  if (pathname === '/admin/products') return t('nav.products', 'Món ăn');
  if (pathname === '/admin/products/create') return t('nav.addProduct', 'Thêm món ăn');
  if (pathname.includes('/admin/products/') && pathname.includes('/edit')) return t('nav.editProduct', 'Chỉnh sửa món ăn');
  if (pathname.startsWith('/admin/categories')) return t('nav.categories', 'Danh mục');
  if (pathname.startsWith('/admin/combos')) return t('nav.combos', 'Combo món');
  if (pathname === '/admin/users') return t('nav.users', 'Khách hàng & Nhân sự');
  if (pathname === '/admin/users/create') return t('nav.addUser', 'Thêm tài khoản');
  if (pathname.startsWith('/admin/users/')) return t('nav.editUser', 'Chi tiết tài khoản');
  if (pathname.startsWith('/admin/memberships')) return t('nav.memberships', 'Thẻ thành viên');
  if (pathname.startsWith('/admin/reviews')) return t('nav.reviews', 'Đánh giá');
  if (pathname.startsWith('/admin/vouchers')) return t('nav.vouchers', 'Voucher');
  if (pathname.startsWith('/admin/flash-sales')) return t('nav.flashSales', 'Flash Sale');
  if (pathname.startsWith('/admin/banners')) return t('nav.banners', 'Banner');
  if (pathname.startsWith('/admin/branches')) return t('nav.branches', 'Chi nhánh');
  if (pathname.startsWith('/admin/staff')) return t('nav.staff', 'Nhân viên');
  if (pathname.startsWith('/admin/payment-methods')) return t('paymentMethods.title', 'Phương thức thanh toán');
  if (pathname.startsWith('/admin/operating-slots')) return t('operatingSlots.title', 'Khung giờ hoạt động');
  if (pathname.startsWith('/admin/settings/print-templates')) return t('printTemplates.title', 'Mẫu in hóa đơn');
  if (pathname.startsWith('/admin/settings')) return t('settings.title', 'Cài đặt');
  if (pathname.startsWith('/admin/roles') || pathname.startsWith('/admin/permissions')) return t('roles.title', 'Vai trò & Phân quyền');
  if (pathname.startsWith('/admin/tables')) return t('tables.title', 'Quản lý bàn');
  if (pathname.startsWith('/admin/articles/comments')) return t('comments.title', 'Quản lý bình luận');
  if (pathname.startsWith('/admin/articles')) return t('articles.title', 'Bài viết & Khuyến mãi');
  if (pathname.startsWith('/admin/audit-logs')) return t('nav.auditLogs', 'Nhật ký hoạt động');

  // Fallback: segment capitalizer
  const segments = pathname.replace('/admin', '').split('/').filter(Boolean);
  if (segments.length > 0) {
    const last = segments[segments.length - 1];
    return last.charAt(0).toUpperCase() + last.slice(1).replace(/-/g, ' ');
  }

  return t('nav.overview', 'Tổng quan');
}
