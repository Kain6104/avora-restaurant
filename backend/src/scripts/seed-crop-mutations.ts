async function main() {
  console.log('--- BẮT ĐẦU SEED TẤT CẢ ĐỘT BIẾN (TỐI THIỂU 3 MẪU MỖI CÂY) ---');
  const allCrops = await prisma.farmCrop.findMany();

  for (const crop of allCrops) {
    const mutations = MUTATIONS_BY_CROP[crop.code];
    if (!mutations) {
      console.log(`Bỏ qua ${crop.code} (chưa định nghĩa)`);
      continue;
    }

    for (const m of mutations) {
      await prisma.farmCropMutation.upsert({
        where: { code: m.code },
        update: {
          name: m.name,
          sourceCropId: crop.id,
          mutationType: m.mutationType,
          rarity: m.rarity,
          description: m.description,
          mutationChance: m.mutationChance,
          yieldMultiplier: m.yieldMultiplier,
          rewardExp: m.rewardExp,
          rewardFarmCoin: m.rewardFarmCoin,
          rewardLoyaltyPoints: m.rewardLoyaltyPoints,
          collectionScore: m.collectionScore,
        },
        create: {
          code: m.code,
          name: m.name,
          sourceCropId: crop.id,
          mutationType: m.mutationType,
          rarity: m.rarity,
          description: m.description,
          mutationChance: m.mutationChance,
          yieldMultiplier: m.yieldMultiplier,
          rewardExp: m.rewardExp,
          rewardFarmCoin: m.rewardFarmCoin,
          rewardLoyaltyPoints: m.rewardLoyaltyPoints,
          collectionScore: m.collectionScore,
        },
      });
    }
    console.log(`✅ Đã đồng bộ ${mutations.length} đột biến cho cây: ${crop.name} (${crop.code})`);
  }

  const count = await prisma.farmCropMutation.count();
  console.log(`🎉 Tổng số đột biến trong cơ sở dữ liệu hiện tại: ${count}`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
